function buildSystemPrompt(mode: ToneMode): string {
  return COMMON_PROMPT + (mode === "formal" ? FORMAL_PROMPT : CASUAL_PROMPT);
}

function hasDirectionFlipRisk(input: string, output: string): boolean {
  const inputHasSaseteMorau = /させてもら/.test(input);
  const outputHasSaseteMorau = /させてもら/.test(output);
  const inputHasTemorau = /てもら|て貰|いただ/.test(input);

  // 元にない「させてもらう」が出現
  if (!inputHasSaseteMorau && inputHasTemorau && outputHasSaseteMorau)
    return true;
  // 「してほしい/してもらう」が「するので」に変化
  if (
    /(してほしい|してもら|いただけると)/.test(input) &&
    /(するので|しますので)/.test(output)
  )
    return true;

  return false;
}

function hasCasualDriftRisk(output: string): boolean {
  // 句点の検出
  const hasPeriod = /。/.test(output);
  // 敬語混入の検出（casualモードでは2つ以上の敬語パターンがあればdrift）
  const politeCount =
    (
      output.match(
        /(です|ます|でしょうか|いたします|お願い)([!！?？\s]|$)/g
      ) ?? []
    ).length;
  return hasPeriod || politeCount >= 2;
}

async function callConvert(
  client: Anthropic,
  systemPrompt: string,
  text: string,
  temperature: number
): Promise<string> {
  const response = await client.messages.create({
    model: "claude-sonnet-4-20250514",
    max_tokens: 1024,
    temperature,
    system: systemPrompt,
    messages: [{ role: "user", content: text }],
  });

  const content = response.content[0];
  if (content.type === "text") {
    return content.text;
  }
  throw new Error("Unexpected response type from Claude API");
}

export async function convertStyle(
  client: Anthropic,
  text: string
): Promise<string> {
  const mode = detectToneMode(text);
  const systemPrompt = buildSystemPrompt(mode);

  let result = await callConvert(
    client,
    systemPrompt,
    text,
    MODE_TEMPERATURE[mode]
  );

  // 方向性反転検知 or casual品質ゲート違反時は temperature: 0.0 で再試行
  if (
    hasDirectionFlipRisk(text, result) ||
    (mode === "casual" && hasCasualDriftRisk(result))
  ) {
    result = await callConvert(client, systemPrompt, text, 0.0);
  }

  return result;
}
