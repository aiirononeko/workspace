type ToneMode = "formal" | "casual";

const MODE_TEMPERATURE: Record<ToneMode, number> = {
  formal: 0.1,
  casual: 0.3,
};
const RETRY_TEMPERATURE = 0.0;

export function detectToneMode(text: string): ToneMode {
  const t = text.normalize("NFKC");
  const formalPatterns =
    /です|ます|ください|でしょうか|いたします|お願い|いただ|ございま|存じ|恐縮/g;
  const casualPatterns =
    /やけど|やで|まじで|めっちゃ|あざ(?:ます|す)|おけ(?:おけ)?|オネシャス|w+$|！{2,}|[~〜～]{2,}/gm;
  const formalCount = (t.match(formalPatterns) ?? []).length;
  const casualCount = (t.match(casualPatterns) ?? []).length;
  return formalCount >= 2 && formalCount >= casualCount ? "formal" : "casual";
}

